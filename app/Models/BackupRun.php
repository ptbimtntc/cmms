<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Support\Facades\Storage;

/**
 * One attempt to create a backup (database or source code). The archive file
 * itself lives in the private `local` disk under backups/, never in public/.
 */
class BackupRun extends Model
{
    public const TYPE_DATABASE = 'database';

    public const TYPE_SOURCE = 'source';

    public const STATUS_RUNNING = 'running';

    public const STATUS_SUCCEEDED = 'succeeded';

    public const STATUS_FAILED = 'failed';

    public const TRIGGER_MANUAL = 'manual';

    public const TRIGGER_SCHEDULED = 'scheduled';

    /** Folder (relative to the private `local` disk) holding finished archives. */
    public const DIRECTORY = 'backups';

    protected $fillable = [
        'type',
        'status',
        'trigger',
        'file_name',
        'file_size',
        'error_message',
        'created_by_user_id',
        'started_at',
        'finished_at',
        'download_started_at',
        'downloaded_by_user_id',
        'file_removed_at',
        'drive_file_id',
        'drive_uploaded_at',
        'drive_error',
        'drive_removed_at',
    ];

    protected function casts(): array
    {
        return [
            'file_size' => 'integer',
            'started_at' => 'datetime',
            'finished_at' => 'datetime',
            'download_started_at' => 'datetime',
            'file_removed_at' => 'datetime',
            'drive_uploaded_at' => 'datetime',
            'drive_removed_at' => 'datetime',
        ];
    }

    public function creator(): BelongsTo
    {
        return $this->belongsTo(User::class, 'created_by_user_id');
    }

    public function downloader(): BelongsTo
    {
        return $this->belongsTo(User::class, 'downloaded_by_user_id');
    }

    public function scopeSucceeded(Builder $query): Builder
    {
        return $query->where('status', self::STATUS_SUCCEEDED);
    }

    public function scopeOfType(Builder $query, string $type): Builder
    {
        return $query->where('type', $type);
    }

    public function isScheduled(): bool
    {
        return $this->trigger === self::TRIGGER_SCHEDULED;
    }

    /** True while the Google Drive copy exists (uploaded and not yet pruned). */
    public function isOnDrive(): bool
    {
        return $this->drive_file_id !== null && $this->drive_removed_at === null;
    }

    /** True only when the archive is still on disk and was not pruned. */
    public function isDownloadable(): bool
    {
        return $this->status === self::STATUS_SUCCEEDED
            && $this->file_removed_at === null
            && $this->file_name !== null
            && Storage::disk('local')->exists($this->relativePath());
    }

    /** Human-readable size without the intl extension (Number::fileSize needs it). */
    public function sizeLabel(): string
    {
        if ($this->file_size === null) {
            return '—';
        }

        $units = ['B', 'KB', 'MB', 'GB'];
        $size = (float) $this->file_size;
        $unit = 0;

        while ($size >= 1024 && $unit < count($units) - 1) {
            $size /= 1024;
            $unit++;
        }

        return number_format($size, $unit === 0 ? 0 : 2, ',', '.').' '.$units[$unit];
    }

    /** Absolute path on the server. Used only server-side; never sent to the browser. */
    public function absolutePath(): string
    {
        return Storage::disk('local')->path($this->relativePath());
    }

    public function relativePath(): string
    {
        // file_name is generated by BackupManager; basename() guards against any stored traversal.
        return self::DIRECTORY.'/'.basename((string) $this->file_name);
    }
}
